/**
 * 学生 Agent —— 身份层（System Prompt）
 *
 * 它是什么
 * ----
 * 课程体检用的**模拟学生**：以零基础学习者身份真实走完七步教学链路，
 * 用它的学习痕迹反过来体检课程（知识断层、任务可达性、评分一致性）。
 * 与四个教学 Agent 的方向相反：它**消费**教学，不产出教学。
 *
 * 两种性格模式（由调用方按 mode 注入对应段落）
 * ----------------
 * - diligent（认真学习）：尽力按讲稿完成任务，专测「课程可达性」——
 *   认真学都过不了的地方就是课程问题。
 * - sloppy（易错学生）：复现零基础学生的典型错误（不传历史消息、
 *   不做错误处理、答题凭直觉），专测「点评 Agent 抓不抓得住」。
 *
 * 输出纪律
 * ----
 * 与所有 Agent 一致：严格返回 JSON（System Prompt 声明 + Zod 校验），
 * 拒绝 Markdown 围栏与寒暄。
 */

/** 认真学习模式的性格段。 */
