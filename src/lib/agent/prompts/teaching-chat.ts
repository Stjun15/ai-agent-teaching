/**
 * 学习页对话态的教学提示词 —— explain / observe / imitate 三步
 *
 * 为什么单独写，而不是直接用 `TEACHER_SYSTEM_PROMPT`
 * ----------------------------------------------
 * 两者服务的**管道不同**，混用会出事故：
 *
 * | | TEACHER_SYSTEM_PROMPT | 本文件的提示词 |
 * |---|---|---|
 * | 消费方 | `/api/agent/explain` 的编排层 | `/api/session/[id]/message` 的 SSE 对话流 |
 * | 输出 | 严格 JSON（`TeacherOutput`，Zod 校验） | Markdown 正文（直接流式显示给学生） |
 * | 失败后果 | Zod 拒绝 → 走兜底 | 学生屏幕上看到一坨 JSON 原文 |
 *
 * 把 JSON 约束带到对话流里是**明确禁止**的：SSE 是逐字吐给学生的，
 * 模型一旦先输出 `{`，学生看到的就是未解析的原始报文。
 * 所以这里复用讲解 Agent 的**教学策略**，但把它改写成可直接阅读的正文形态。
 *
 * 与临时提示词（loop.ts 的 PROVISIONAL_SYSTEM_PROMPT）的分工
 * --------------------------------------------------
 * 临时提示词要求「简洁直接，先给结论再给理由」——那是**答疑**的口径，
 * 用在讲概念上就是「一句话打发学生」。学生的原话反馈：
 * 「概念讲解就一句话吗？应该先仔细讲讲，然后再给出实例，之后再让用户模仿。」
 * 本提示词专门管讲解场景；答疑场景保留临时提示词不变。
 *
 * 两份提示词的分工
 * --------------
 * - `TEACHING_EXPLAIN_PROMPT`：概念讲解步专用。走**通关模式**——
 *   门禁确认 → 为什么需要 → 核心概念 → 防踩坑 → 两层概念测验（选择题 + 动手判断），
 *   不含任何模仿/写代码环节。两题全对才算「概念过关」，错任何一题换类比重讲。
 * - `TEACHING_CHAT_SYSTEM_PROMPT`：观察示范 / 动手模仿步共用。
 *   学生已经听过概念讲解，现在要「看清对的」再「自己写」，
 *   所以保留「五、现在轮到你」作为终点。
 *
 * 依据
 * ----
 * - 三步来自 `StepType` 的 `explain` / `observe` / `imitate`
 *   （`learning-steps.ts` 头部已考据：对应「认知学徒制」的示范环节）。
 * - observe / imitate 落脚到「学生动手」，对应 `00-MASTER.md` 教学流程第 2 步
 *   「学生完成场景」，与 `02-agent-system.md` 讲解 Agent 行为准则第 3 条
 *   「每讲完一个概念，问一个检验问题」。
 * - 「不直接给答案」是讲解 Agent 行为准则第 1 条，本文件在第 5 步重申。
 *   explain 步的「检验问题」同样是问、不给答案。
 */

